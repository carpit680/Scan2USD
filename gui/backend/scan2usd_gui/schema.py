"""Parameter catalog: every SceneConfig field and CLI option with tooltips."""

from __future__ import annotations

from typing import Any, Literal

ParamType = Literal[
    "string",
    "int",
    "float",
    "bool",
    "path",
    "enum",
    "string_list",
    "json",
]

WidgetType = Literal[
    "slider",
    "number",
    "select",
    "toggle",
    "path",
    "tags",
    "text",
    "json",
]

HelpLevel = Literal["essential", "advanced"]


def _infer_widget(
    type: ParamType,
    *,
    enum: list[str] | None,
    min: float | None,
    max: float | None,
    widget: WidgetType | None,
) -> WidgetType:
    if widget:
        return widget
    if type == "bool":
        return "toggle"
    if type == "enum" or enum:
        return "select"
    if type == "path":
        return "path"
    if type == "string_list":
        return "tags"
    if type == "json":
        return "json"
    if type in {"int", "float"} and min is not None and max is not None:
        return "slider"
    if type in {"int", "float"}:
        return "number"
    return "text"


def _p(
    *,
    id: str,
    label: str,
    type: ParamType,
    group: str,
    tooltip: str,
    default: Any = None,
    config_path: str | None = None,
    command: str | None = None,
    enum: list[str] | None = None,
    min: float | None = None,
    max: float | None = None,
    step: float | None = None,
    guide_anchor: str | None = None,
    required: bool = False,
    widget: WidgetType | None = None,
    help_level: HelpLevel = "advanced",
    path_kind: Literal["file", "dir", "any"] = "any",
    path_ext: str | None = None,
    default_from: str | None = None,
    config_default_from: str | None = None,
) -> dict[str, Any]:
    w = _infer_widget(type, enum=enum, min=min, max=max, widget=widget)
    if step is None and w == "slider":
        step = 1 if type == "int" else 0.01
    return {
        "id": id,
        "label": label,
        "type": type,
        "group": group,
        "tooltip": tooltip,
        "default": default,
        "config_path": config_path,
        "command": command,
        "enum": enum,
        "min": min,
        "max": max,
        "step": step,
        "guide_anchor": guide_anchor,
        "required": required,
        "widget": w,
        "help_level": help_level,
        "path_kind": path_kind,
        "path_ext": path_ext,
        "default_from": default_from,
        "config_default_from": config_default_from,
    }


