        id=f"cmd.{command}.{name}",
        label=label,
        type=type,
        group=f"command:{command}",
        default=default,
        command=command,
        config_path=f"_pos_{name}" if positional else name,
        enum=enum,
        required=required,
        tooltip=tooltip,
        guide_anchor=guide_anchor,
        path_kind=path_kind,
        path_ext=path_ext,
        default_from=default_from,
